function parseFilterRow(row: string): PokemonFilterRecord {
  const [id, generationId, types, colorApiName, kanaRow, specialFlag, baseStatTotal] = row.split("|");

  return {
    id: Number(id),
    generationId: Number(generationId) as GenerationId,
    typeNamesApi: types.split(",") as PokemonTypeName[],
    colorApiName: colorApiName as PokemonColorName,
    kanaRow: kanaRow as KanaRow,
    isLegendaryOrMythical: specialFlag === "1",
    baseStatTotal: Number(baseStatTotal),
  };
}

export const pokemonFilterIndex: PokemonFilterRecord[] = pokemonFilterRows.map(parseFilterRow);

export function countGenerationPokemon(generation: (typeof generationOptions)[number]): number {
  return generation.end - generation.start + 1;
}

function sameGenerationSelection(generationIds: GenerationId[]): boolean {
  if (generationIds.length !== allGenerationIds.length) {
    return false;
  }

  const selected = new Set(generationIds);
  return allGenerationIds.every((id) => selected.has(id));
}

export function hasCustomPokemonFilters(filters: PokemonFilterState): boolean {
  return (
    !sameGenerationSelection(filters.generationIds) ||
    filters.starterOnly ||
    filters.legendaryOrMythicalOnly ||
    filters.typeNamesApi.length > 0 ||
    filters.baseStat600PlusOnly ||
    filters.megaEvolutionOnly ||
    filters.colorNames.length > 0 ||
    filters.kanaRows.length > 0 ||
    filters.popularOnly
  );
}

export function filterSpeciesIds(filters: PokemonFilterState): number[] {
  const selectedGenerations = new Set(filters.generationIds);
  const selectedTypes = new Set(filters.typeNamesApi);
  const selectedColors = new Set(filters.colorNames);
  const selectedKanaRows = new Set(filters.kanaRows);

  return pokemonFilterIndex
    .filter((record) => {
      if (!selectedGenerations.has(record.generationId)) {
        return false;
      }

      if (filters.starterOnly && !starterEvolutionIds.has(record.id)) {
        return false;
      }

      if (filters.legendaryOrMythicalOnly && !record.isLegendaryOrMythical) {
        return false;
      }

      if (selectedTypes.size > 0 && !record.typeNamesApi.some((typeName) => selectedTypes.has(typeName))) {
        return false;
      }

      if (filters.baseStat600PlusOnly && record.baseStatTotal < 600) {
        return false;
      }

      if (filters.megaEvolutionOnly && !megaEvolutionFamilyIds.has(record.id)) {
        return false;
      }

      if (selectedColors.size > 0 && !selectedColors.has(record.colorApiName)) {
        return false;
      }

      if (selectedKanaRows.size > 0 && !selectedKanaRows.has(record.kanaRow)) {
        return false;
      }

      return !filters.popularOnly || popularPokemonIds.has(record.id);
    })
    .map((record) => record.id);
}

function labelsForGenerationSelection(generationIds: GenerationId[]): string[] {
  if (sameGenerationSelection(generationIds)) {
    return [];
  }

  const selected = new Set(generationIds);
  return generationOptions.filter((generation) => selected.has(generation.id)).map((generation) => generation.label);
}

export function formatPokemonFilterSummary(filters: PokemonFilterState): string | undefined {
  if (!hasCustomPokemonFilters(filters)) {
    return undefined;
  }

  const parts = [
    ...labelsForGenerationSelection(filters.generationIds),
    ...(filters.starterOnly ? ["御三家"] : []),
    ...(filters.legendaryOrMythicalOnly ? ["伝説・幻"] : []),
    ...pokemonTypeOptions.filter((option) => filters.typeNamesApi.includes(option.apiName)).map((option) => option.label),
    ...(filters.baseStat600PlusOnly ? ["種族値600以上"] : []),
    ...(filters.megaEvolutionOnly ? ["メガシンカ"] : []),
    ...pokemonColorOptions.filter((option) => filters.colorNames.includes(option.apiName)).map((option) => `${option.label}色`),
    ...kanaRowOptions.filter((option) => filters.kanaRows.includes(option.id)).map((option) => option.label),
    ...(filters.popularOnly ? ["人気100"] : []),
  ];

  return parts.join(" / ");
}
